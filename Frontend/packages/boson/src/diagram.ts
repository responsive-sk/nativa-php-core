/**
 * diagram.ts — the landing's stack diagram, and the only reason this bundle
 * imports Mermaid at runtime.
 *
 * The chunk is NOT loaded with the page: the inline module in
 * `SiteHomepageSurface` waits until the figure is near the viewport and only
 * then imports this file, so the landing keeps its six-request first paint and
 * its measured LCP. Everything Mermaid costs — the parser, the layout engine,
 * the font metrics — is paid by the reader who actually scrolls to the tree.
 *
 * The source of the diagram travels in `data-mermaid` on the figure, generated
 * from the same copy array the list below it renders, so the picture and the
 * list cannot disagree about what the stack is.
 */
import mermaid from 'mermaid';

const figure = document.querySelector<HTMLElement>('[data-mermaid]');

if (figure) {
  const source = figure.dataset.mermaid ?? '';

  // The palette is read off the figure, not hardcoded: the landing inherits
  // the theme's ink, and a diagram drawn in a fixed colour scheme is a white
  // card on a dark page (which is exactly what the first build produced).
  const ink = getComputedStyle(figure).color || '#1a1a1a';
  const channels = ink.match(/rgba?\(([^)]+)\)/)?.[1]?.split(',').slice(0, 3).map(Number) ?? [26, 26, 26];
  const [red, green, blue] = channels.map((value) => (Number.isFinite(value) ? value : 26));
  const surface = `rgba(${red}, ${green}, ${blue}, 0.06)`;
  const edge = `rgba(${red}, ${green}, ${blue}, 0.4)`;

  mermaid.initialize({
    startOnLoad: false,
    // The page's own palette, not Mermaid's default blue: the diagram sits on
    // the same paper as the section and must not look pasted in.
    theme: 'base',
    themeVariables: {
      background: 'transparent',
      primaryColor: surface,
      primaryTextColor: ink,
      primaryBorderColor: edge,
      secondaryColor: surface,
      tertiaryColor: 'transparent',
      lineColor: edge,
      textColor: ink,
      edgeLabelBackground: 'transparent',
      clusterBkg: surface,
      clusterBorder: edge,
      fontFamily: 'inherit',
      fontSize: '14px',
    },
    // The source is generated by the server, not typed by a visitor — but the
    // diagram renders on a public page, and `strict` is the level that keeps
    // an injected label from becoming an HTML sink.
    securityLevel: 'strict',
    // dagre, not elk. Measured 2026-11-19 on this landing: the default layout
    // engine pulled 24 further chunks and 2.4 MB to draw one 9-node flowchart
    // — `elk` alone is 1.5 MB. The tree is small and acyclic, so dagre draws
    // the same picture out of a chunk that is already on the wire.
    layout: 'dagre',
    // Mermaid 12 dropped the separate `defaultRenderer` flowchart key: there
    // is one wrapper renderer now, and `layout: 'dagre'` above is the choice
    // that still exists.
  });

  void mermaid
    .render('site-diagram-svg', source)
    .then(({ svg }) => {
      figure.innerHTML = svg;
      figure.dataset.mermaidRendered = 'true';
      figure.removeAttribute('aria-busy');
    })
    .catch(() => {
      // A diagram that cannot be drawn must not leave a blank box: the list
      // below the figure is the same tree in text, so the figure simply stays
      // hidden and the section reads as it did before the diagram existed.
      figure.hidden = true;
      figure.removeAttribute('aria-busy');
    });
}
